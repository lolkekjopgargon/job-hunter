#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
agent_letter_engine.py - Autonomous AI Cover Letter Synthesizer.

Generates tailored, authentic, living cover letters adhering strictly to
application_rules.md (Section 16, 17, 39) and candidate_facts.md.

Design principles:
- Plain text only (NO markdown links, NO bold, NO asterisks, NO bullet points).
- Pure author speech: links and contacts are handled by Planka TaskLists & dispatcher.
- Starts strictly with 'День добрый!'.
- First-person practitioner voice, humble, self-ironic, focusing on hands-on realities.
- Analyzes vacancy specialization (FTUE, LiveOps, Core/Combat, Level Design,
  Narrative, VoiceOver, 3D Environment, Architecture AGR, Event Design, Creative Producer).
"""

import os
import sys
import re
from typing import Dict, Any, Optional

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, "..", ".."))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)


def generate_tailored_cover_letter(
    role_cat: str,
    title: str,
    employer: str,
    description: str = "",
    taxonomy: Optional[Dict[str, Any]] = None
) -> str:
    """
    Synthesizes a tailored, authentic living cover letter under Section 16 & 39 rules.
    Returns clean author speech without hardcoded links or contact blocks.
    """
    text_lower = f"{title} {employer} {description}".lower()

    # 1. Game Design Sub-specializations
    if role_cat == "game_designer":
        # Sub-type A: FTUE / Onboarding / First Session
        if any(k in text_lower for k in ["ftue", "first time user", "онбординг", "первый опыт", "первая сессия", "ранний опыт"]):
            return (
                "День добрый!\n\n"
                "В онбординге и первых минутах игры мне важно, чтобы игрок как можно быстрее почувствовал геймплей руками, "
                "а не продирался сквозь стены обучающих текстов и принудительных стрелочек интерфейса. Особенно в открытом мире "
                "или экшене: игрок должен сразу сесть за руль или получить управление, почувствовать динамику, а правила раскрываются через действие.\n\n"
                "Обычно проектирую флоу первой сессии так, чтобы за первые три-пять минут игрок получил понятный позитивный опыт, "
                "разобрался в базовых правилах и захотел остаться. Прототипы и логику экранов собираю быстро, при этом проверку шагов "
                "автоматизирую скриптами, чтобы отслеживать, где новички теряются или бросают сессию. В геймдев пришел из нарратива "
                "(Owlcat Games, VEA Games), поэтому обучение всегда стараюсь делать органичной частью игрового мира."
            )

        # Sub-type B: LiveOps / Events / In-Game Economy
        if any(k in text_lower for k in ["liveops", "live ops", "ивент", "сезон", "лайвопс", "монетиз", "экономик", "battle pass", "боевой пропуск"]):
            return (
                "День добрый!\n\n"
                "В LiveOps и сезонных событиях мне важно, чтобы ивенты не превращались в рутинный сбор чек-листов, а давали игроку "
                "реальный игровой повод зайти сегодня и пощупать новые условия. При этом награды должны двигать прогресс, но не ломать "
                "долгосрочную экономику игры инфляцией.\n\n"
                "Когда дело доходит до баланса наград и ивентовых циклов, я стараюсь не крутить таблицы вручную наугад: обычно пишу скрипты "
                "симуляций, прогоняю сценарии накопления валюты и смотрю, где кривая наград проседает или образуется избыточный дефицит. "
                "В геймдев пришел со стороны нарратива и режиссуры (Owlcat Games, VEA Games, Щукинский институт), поэтому события всегда "
                "подаю как живую часть игрового мира с понятным контекстом."
            )

        # Sub-type C: Level Design / Tech LD
        if any(k in text_lower for k in ["level designer", "левел", "дизайнер уровней", "level design"]):
            return (
                "День добрый!\n\n"
                "В левел-дизайне для меня ключевое — навигация игрока и темпоритм локации: геометрия и свет должны сами вести взгляд, "
                "без необходимости вешать маркеры на каждый угол. Обычно сначала собираю черновой блокаут в Unreal Engine, прогоняю боевые энкаунтеры "
                "и смотрю, где игрок путается, застревает или теряет ощущение динамики.\n\n"
                "Хорошо ориентируюсь в технических требованиях: оптимизация геометрии, метрики прыжков, укрытия, линии видимости и триггеры логики на Blueprints. "
                "Режиссерское образование (Театральный институт им. Щукина) помогает держать композицию пространства и плановость кадра, "
                "а опыт в Owlcat Games — органично связывать пространство сцены с сюжетом."
            )

        # Sub-type D: Core Gameplay / Systems / Generalist (Benchmark 16.11)
        return (
            "День добрый!\n\n"
            "В системном дизайне обычно сам собираю механику от идеи до прототипа: продумываю, что игрок делает руками, какие правила работают "
            "и как системы цепляются друг за друга. Часто механика на бумаге выглядит стройно, а в прототипе выясняется, что игрок считывает ее иначе, "
            "поэтому мне важно быстро проверить механику в игре. Из личных проектов делал соревновательный PvP с карточными синергиями и балансную архитектуру боевой системы.\n\n"
            "Прототипы собираю с AI-инструментами: сам задаю архитектуру и логику, а рутинную сборку и симуляции автоматизирую скриптами, "
            "чтобы смотреть, где плывет баланс или вылезают имбовые стратегии. В геймдев пришел со стороны нарратива (Owlcat Games, VEA Games), "
            "поэтому мне важно, чтобы правила игры работали на общее ощущение от мира, а не существовали отдельно в вакууме."
        )

    # 2. Narrative & Dialogue & VoiceOver
    if role_cat in ["narrative_designer", "dialogue_director"]:
        # VoiceOver / Audio Designer
        if any(k in text_lower for k in ["voiceover", "voice", "озвучк", "диктор", "звук", "аудио", "воис"]):
            return (
                "День добрый!\n\n"
                "В работе с озвучкой и репликами опираюсь на режиссерское образование (Театральный институт им. Щукина) "
                "и собственный актерский опыт озвучания в Mafia: Definitive Edition и Cyberpunk 2077. На слух сразу слышу, когда реплика "
                "звучит неестественно, интонация ломает характер или тайминг фразы не попадает в динамику геймплея.\n\n"
                "В Owlcat Games на The Expanse: Osiris Reborn ставил диалоговые сцены в Unreal Engine: работал с камерами, таймингами подачи фраз "
                "и эмоциональным напряжением в кадре. Умею давать актерам точные режиссерские задачи и выстраивать пайплайн от сценария до финальной интеграции в движок."
            )

        # Narrative Designer Benchmark
        return (
            "День добрый!\n\n"
            "В Owlcat Games на The Expanse: Osiris Reborn я ставил диалоговые сцены в Unreal Engine и отсматривал реплики в контексте происходящего на экране. "
            "В диалогах обычно отталкиваюсь от контекста сцены: кто говорит, зачем и что игрок уже знает к этой секунде, поэтому раскадровку, тайминги и текст собирал вместе.\n\n"
            "В VEA Games работал с лором, NPC и сайд-квестами. По образованию я режиссер (Театральный институт им. Щукина), плюс озвучивал персонажей в играх. "
            "Актерский опыт помогает на слух замечать фальшь в диалогах, а режиссура — держать арку сцены и внимание игрока."
        )

    # 3. 3D Generalist / Artist Sub-specializations
    if role_cat in ["3d_generalist", "3d_artist"]:
        # Architecture / AGR / Urban
        if any(k in text_lower for k in ["агр", "архитектур", "фасад", "генплан", "urban", "чертеж"]):
            return (
                "День добрый!\n\n"
                "Работаю с трехмерным моделированием архитектурных объектов и городской среды. По чертежам и материалам АГР моделирую здания "
                "с соблюдением точных пропорций, высотных отметок и фасадных членений.\n\n"
                "Держу чистую топологию без лишней плотности полигонов, аккуратно готовлю модели к рендеру и интеграции в окружение. "
                "Работаю в связке Blender, Unreal Engine и пакетах постобработки. Пространственное мышление и работа с чертежами подкреплены "
                "профильным образованием (Театральный институт им. Щукина, режиссура), поэтому четко держу геометрию, ритм фасадов и объемно-пространственную композицию."
            )

        # Exhibition / Event / Spatial Design
        if any(k in text_lower for k in ["выставочн", "стенд", "event", "экспозици", "интерьер", "пространств"]):
            return (
                "День добрый!\n\n"
                "Занимаюсь трехмерным моделированием и визуализацией пространств в Blender, Unreal Engine и DaVinci Resolve. "
                "В выставочном и пространственном дизайне для меня главное — грамотно совместить эргономику потоков посетителей, "
                "акцентные зоны и кинематографическую подачу света.\n\n"
                "Могу быстро собирать объемные концепты, ставить свет и делать динамические облеты камеры для согласования с клиентом, "
                "без затягивания сроков на долгие статичные рендеры. Имею высшее режиссерское образование (Театральный институт им. Щукина), "
                "поэтому отлично чувствую композицию пространства, масштаб и визуальные фокусы внимания."
            )

        # Character Artist (Honest Disclaimer)
        if any(k in text_lower for k in ["персонаж", "character", "скульпт", "zbrush"]):
            return (
                "День добрый!\n\n"
                "Сразу честно обозначу свой профиль: я работаю как 3D Generalist со связкой Unreal Engine 5, Blender и DaVinci Resolve. "
                "Мой сильный фокус — сборка сцен, свет, операторские планы, фотосканы, ретопология и hard-surface элементы. Скульптинг органической "
                "персонажки с нуля в ZBrush не является моей узкой специализацией, поэтому если в задачах требуется чисто анатомический скульптинг с нуля — лучше сразу свериться.\n\n"
                "Если же вам нужен специалист, который может быстро собрать персонажа в сцене UE5, настроить материалы, свет, камеру, подогнать "
                "готовую геометрию под пайплайн и подать сцену кинематографично — это полностью мой рабочий пайплайн. В студии CGF занимался "
                "real-time технологиями и R&D. Имею профильное режиссерское образование (Театральный институт им. Щукина), поэтому держу композицию и драматургию кадра."
            )

        # Environment Artist / General 3D
        return (
            "День добрый!\n\n"
            "Работаю в связке Unreal Engine 5, Blender и DaVinci Resolve. При сборке локаций обычно сначала выставляю общие объемы, "
            "свет и траектории движения камеры, чтобы окружение работало как цельная сцена, а уже затем насыщаю его пропсами и деталями.\n\n"
            "Владею полным пайплайном: блокауты, моделирование, работа с трим-листами и тайлами, обработка фотосканов и чистая топология. "
            "В студии CGF работал в R&D с real-time графикой и нейросетевыми инструментами. Имею профильное режиссерское образование "
            "(Театральный институт им. Щукина), поэтому всегда держу драматургию кадра, плановость и атмосферу окружения."
        )

    # 4. Creative Producer & Video Editor
    if role_cat in ["creative_producer", "video_editor"]:
        return (
            "День добрый!\n\n"
            "Монтирую в DaVinci Resolve, собирал промо-видео, презентации для инвесторов и кинематографические превизы. В промо я обычно сначала собираю понятный ритм и хук, а уже потом наращиваю визуал.\n\n"
            "Весь цикл обычно веду сам: от идеи и раскадровки до сборки камер в Unreal Engine и финального монтажа с цветом. В студии CGF работал с real-time пайплайном и R&D. Имею профильное режиссерское образование (Театральный институт им. Щукина), поэтому держу драматургию и внимание зрителя в кадре."
        )

    # 5. Fallback / AI Product
    return (
        "День добрый!\n\n"
        "Для своих инструментов и прототипов использую AI-assisted development: сам задаю архитектуру, логику и поведение системы, а реализацию собираю вместе с AI. Если какую-то проверку приходится повторять руками десять раз, я почти всегда сначала думаю, можно ли это отдать скрипту или агенту.\n\n"
        "В CGF занимался R&D в департаменте нейросетей. Из личных проектов делал связку Unreal Engine 5 с локальными LLM для динамических NPC и RAG-системы с семантическим поиском."
    )
